#!/usr/bin/env python3
"""Generate the Chinese-patch text table: Shift-JIS code -> real character.

The CK-GAL patch stores its Chinese script as Shift-JIS *code points* and paints
the real glyph into the game's bitmap font. Decoding those bytes as CP932 gives
unrelated Japanese kanji, so any text path that wants actual characters (vector
font rendering, backlog, saves) has to go the other way round:

    sjis code -> atlas cell   (tools/tables/wa2_cell_map_cn.tsv, from the exe)
    cell >= 748: character is wa2.cht.txt index (cell - 748)
    cell <  748: the glyph is still the original symbol, so the CP932 decoding
                 is already correct and no entry is needed.

Usage:
    python3 tools/gen_cn_text.py

Writes src/codec/cn_text.rs.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CELL_MAP = os.path.join(ROOT, "tools", "tables", "wa2_cell_map_cn.tsv")
CHT = os.path.join(ROOT, "tools", "tables", "wa2.cht.txt")
OUT = os.path.join(ROOT, "src", "codec", "cn_text.rs")

# Cells below this hold the original punctuation/kana; the Chinese glyphs start
# here (matches wa2refont's read_character_encoding start_pos).
CN_CELL_BASE = 748


def read_cell_map(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        try:
            code = int(parts[0], 16)
            cell = int(parts[2])
        except ValueError:
            continue
        out[code] = cell
    return out


def main():
    cell_of = read_cell_map(CELL_MAP)
    # wa2.cht.txt is wrapped/formatted; the whitespace is not part of the list.
    cht = [c for c in open(CHT, encoding="utf-8").read() if not c.isspace()]

    table = []
    skipped = 0
    for code, cell in sorted(cell_of.items()):
        if cell < CN_CELL_BASE:
            continue
        idx = cell - CN_CELL_BASE
        if idx >= len(cht):
            # A glyph the atlas has but the Chinese char list does not cover.
            # None of these appear in the script, so leave the CP932 decoding.
            skipped += 1
            continue
        table.append((code, cht[idx]))

    lines = [
        "//! Generated by tools/gen_cn_text.py - do not edit.",
        "//!",
        "//! The CK-GAL Chinese patch writes its script as Shift-JIS code points",
        "//! and paints the real glyph into the bitmap font, so decoding the bytes",
        "//! as CP932 yields unrelated Japanese kanji. This table maps those code",
        "//! points back to the character that is actually drawn:",
        "//!",
        "//!   code -> atlas cell  (wa2_cell_map_cn.tsv, from WA2_chs.exe)",
        "//!   cell -> char        (wa2.cht.txt index cell - 748)",
        "//!",
        "//! Cells below 748 are the original punctuation and kana, whose CP932",
        "//! decoding is already correct, so they are not listed here.",
        "//!",
        "//! Sorted by code; look up with binary_search_by_key.",
        "pub const CN_TO_UNICODE: &[(u16, char)] = &[",
    ]
    for code, ch in table:
        lines.append("    (0x{:04X}, '\\u{{{:04X}}}'),".format(code, ord(ch)))
    lines.append("];")
    lines.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print("cn_text: {} codes -> {} ({} atlas cells beyond wa2.cht.txt)".format(
        len(table), OUT, skipped))


if __name__ == "__main__":
    main()
